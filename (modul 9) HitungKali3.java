
package Modul09;  //folder untuk kelas ini


public class HitungKali3 {  //memberika kelas ini akses public supaya dapat di akses dari kelas/package lain
    public static void main(String[] args) {  //kalimat kode pertama untuk semua kode di Java
        int a,b;  //mengubah data a dan b menjadi integer
        int hasil;  //mengubah data hasil menjadi integer
        
        a=3;  //menetapkan value a menjadi 3
        b=4;  //menetapkan value b menjadi 4
        hasil=a*b;  //menetapkan variabel hasil menjadi hasil dari a kali b
        
        System.out.println("Hasil dari perkalian 3 dan 4 adalah : "+hasil);  //mencetak string hasil dari rumus a kali b
    }  //akhir dari main
}  //akhir dari kelas ini
